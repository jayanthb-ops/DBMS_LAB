-- 1. Cars arranged by manufacturing year
SELECT *
FROM CAR
ORDER BY YEAR ASC;

-- 2. Number of accidents involving Lancer cars
SELECT COUNT(DISTINCT REPORT_NUM) AS ACCIDENT_COUNT
FROM PARTICIPATED P
JOIN CAR C ON P.REG_NUM = C.REG_NUM
WHERE C.MODEL = 'Lancer';

-- 3. Number of people owning cars involved in accidents in 2008
SELECT COUNT(DISTINCT O.DRIVER_ID) AS PEOPLE_COUNT
FROM OWNS O
JOIN PARTICIPATED P
    ON O.DRIVER_ID = P.DRIVER_ID
   AND O.REG_NUM = P.REG_NUM
JOIN ACCIDENT A
    ON P.REPORT_NUM = A.REPORT_NUM
WHERE YEAR(A.ACCIDENT_DATE) = 2008;

-- 4. Participation records in descending damage order
SELECT *
FROM PARTICIPATED
ORDER BY DAMAGE_AMOUNT DESC;

-- 5. Average damage amount
SELECT AVG(DAMAGE_AMOUNT) AS AVERAGE_DAMAGE
FROM PARTICIPATED;

-- 6. Delete participation records below average damage
DELETE FROM PARTICIPATED
WHERE DAMAGE_AMOUNT < (
    SELECT AVG_DAMAGE
    FROM (
        SELECT AVG(DAMAGE_AMOUNT) AS AVG_DAMAGE
        FROM PARTICIPATED
    ) X
);

-- 7. Driver names whose damage exceeds average damage
SELECT DISTINCT P.NAME
FROM PERSON P
JOIN PARTICIPATED PA ON P.DRIVER_ID = PA.DRIVER_ID
WHERE PA.DAMAGE_AMOUNT > (
    SELECT AVG(DAMAGE_AMOUNT)
    FROM PARTICIPATED
);

-- 8. Maximum damage amount
SELECT MAX(DAMAGE_AMOUNT) AS MAXIMUM_DAMAGE
FROM PARTICIPATED;

