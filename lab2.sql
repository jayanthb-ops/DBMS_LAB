-- i. Branch name and assets in lakhs
SELECT BRANCH_NAME, ASSETS/100000 AS ASSETS_IN_LAKHS
FROM BRANCH;

-- ii. Customers who have an account at every branch in Delhi
SELECT D.CUSTOMER_NAME
FROM DEPOSITER D
JOIN BANKACCOUNT A ON D.ACCNO = A.ACCNO
JOIN BRANCH B ON A.BRANCH_NAME = B.BRANCH_NAME
WHERE B.BRANCH_CITY = 'Delhi'
GROUP BY D.CUSTOMER_NAME
HAVING COUNT(DISTINCT B.BRANCH_NAME) = (
    SELECT COUNT(*)
    FROM BRANCH
    WHERE BRANCH_CITY = 'Delhi'
);

-- iii. Customers who have a loan but no account
SELECT DISTINCT BO.CUSTOMER_NAME
FROM BORROWER BO
WHERE NOT EXISTS (
    SELECT 1
    FROM DEPOSITER D
    WHERE D.CUSTOMER_NAME = BO.CUSTOMER_NAME
);

-- iv. Customers with both account and loan at Bengaluru branch
SELECT DISTINCT D.CUSTOMER_NAME
FROM DEPOSITER D
JOIN BANKACCOUNT A ON D.ACCNO = A.ACCNO
JOIN BRANCH B ON A.BRANCH_NAME = B.BRANCH_NAME
JOIN BORROWER BO ON D.CUSTOMER_NAME = BO.CUSTOMER_NAME
JOIN LOAN L ON BO.LOAN_NUMBER = L.LOAN_NUMBER
WHERE B.BRANCH_CITY = 'Bangalore'
  AND L.BRANCH_NAME = B.BRANCH_NAME;

-- v. Branches having assets greater than ALL Bombay branches
SELECT BRANCH_NAME
FROM BRANCH
WHERE ASSETS > ALL (
    SELECT ASSETS
    FROM BRANCH
    WHERE BRANCH_CITY = 'Bombay'
);

-- vi. Delete all accounts at branches located in Bombay
DELETE FROM DEPOSITER
WHERE ACCNO IN (
    SELECT ACCNO
    FROM BANKACCOUNT
    WHERE BRANCH_NAME IN (
        SELECT BRANCH_NAME
        FROM BRANCH
        WHERE BRANCH_CITY = 'Bombay'
    )
);

DELETE FROM BANKACCOUNT
WHERE BRANCH_NAME IN (
    SELECT BRANCH_NAME
    FROM BRANCH
    WHERE BRANCH_CITY = 'Bombay'
);

-- vii. Increase balance of all accounts by 5%
-- vii. Increase balance by 5% only for accounts
-- having a balance greater than 50000

UPDATE BANKACCOUNT
SET BALANCE = BALANCE * 1.05
WHERE BALANCE > 50000;


-- viii. View total loan amount for each branch
CREATE VIEW BRANCH_LOAN_TOTAL AS
SELECT BRANCH_NAME, SUM(AMOUNT) AS TOTAL_LOAN_AMOUNT
FROM LOAN
GROUP BY BRANCH_NAME;

