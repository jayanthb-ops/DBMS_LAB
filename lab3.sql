-- 1. Employee numbers working on projects in Bengaluru,
-- Hyderabad or Mysore
SELECT DISTINCT E.EMPNO
FROM EMPLOYEE E
JOIN ASSIGNED_TO A ON E.EMPNO = A.EMPNO
JOIN PROJECT P ON A.PNO = P.PNO
WHERE P.PLOC IN ('Bangalore','Hyderabad','Mysore');

-- 2. Employees who did not receive incentives
SELECT E.EMPNO, E.ENAME
FROM EMPLOYEE E
LEFT JOIN INCENTIVES I ON E.EMPNO = I.EMPNO
WHERE I.EMPNO IS NULL;

-- 3. Employees working on projects located in the same
-- location as their department
SELECT E.ENAME, E.EMPNO, D.DNAME, A.JOB_ROLE,
       D.DLOC, P.PLOC
FROM EMPLOYEE E
JOIN DEPT D ON E.DEPTNO = D.DEPTNO
JOIN ASSIGNED_TO A ON E.EMPNO = A.EMPNO
JOIN PROJECT P ON A.PNO = P.PNO
WHERE D.DLOC = P.PLOC;