-- 1. Display cars ordered by year
SELECT *
FROM CAR
ORDER BY YEAR;

-- 2. Count accidents involving Lancer cars
SELECT * FROM PARTICIPATED P
JOIN CAR C ON P.REG_NUM = C.REG_NUM
WHERE C.MODEL = 'Lancer';

-- 3. Count people owning cars involved in accidents in 2008
SELECT COUNT(DISTINCT O.DRIVER_ID)
FROM OWNS O
JOIN PARTICIPATED P ON O.DRIVER_ID = P.DRIVER_ID
JOIN ACCIDENT A ON P.REPORT_NUM = A.REPORT_NUM
WHERE YEAR(A.ACCIDENT_DATE) = 2008;

-- 4. Display participation records in descending damage order
SELECT *
FROM PARTICIPATED
ORDER BY DAMAGE_AMOUNT DESC;

-- 5. Average damage amount
SELECT AVG(DAMAGE_AMOUNT)
FROM PARTICIPATED;

-- 6. Delete records whose damage is below average
DELETE FROM PARTICIPATED
WHERE DAMAGE_AMOUNT < (
    SELECT AVG_DAMAGE
    FROM (
        SELECT AVG(DAMAGE_AMOUNT) AS AVG_DAMAGE
        FROM PARTICIPATED
    ) AS T
);

-- 7. Find drivers whose damage amount is greater than average
SELECT DRIVER_ID
FROM PARTICIPATED
WHERE DAMAGE_AMOUNT > (
    SELECT AVG(DAMAGE_AMOUNT)
    FROM PARTICIPATED
);

-- 8. Find maximum damage amount
SELECT MAX(DAMAGE_AMOUNT)
FROM PARTICIPATED;

